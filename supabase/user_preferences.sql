-- Safe to rerun for the same schema. No existing user data is deleted.
begin;

create table if not exists public.user_preferences (
  user_id uuid primary key references auth.users(id) on delete cascade,
  show_animated_lyrics boolean not null default true,
  equalizer_enabled boolean not null default false,
  ambient_color_enabled boolean not null default true,
  auto_download_enabled boolean not null default false,
  audio_quality text not null default 'High'
    constraint user_preferences_audio_quality_check
    check (audio_quality in ('Standard', 'High', 'Extreme')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

comment on table public.user_preferences is
  'One account-wide preference row per Supabase Auth user; created lazily by the app.';
comment on column public.user_preferences.show_animated_lyrics is
  'Shows the animated single lyric line below album artwork in the playing view.';
comment on column public.user_preferences.equalizer_enabled is
  'Persists the existing Equalizer control; does not implement an audio equalizer.';
comment on column public.user_preferences.ambient_color_enabled is
  'Persists the existing Dynamic Ambient Color control.';
comment on column public.user_preferences.auto_download_enabled is
  'Persists the existing Auto-Downloads control; does not implement downloads.';
comment on column public.user_preferences.audio_quality is
  'Persists the existing Audio Quality selection; does not transcode or select streams.';

create or replace function public.set_user_preferences_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists user_preferences_updated_at on public.user_preferences;
create trigger user_preferences_updated_at
  before update on public.user_preferences
  for each row execute function public.set_user_preferences_updated_at();

alter table public.user_preferences enable row level security;

drop policy if exists user_preferences_select_own on public.user_preferences;
create policy user_preferences_select_own
  on public.user_preferences for select to authenticated
  using ((select auth.uid()) = user_id);

drop policy if exists user_preferences_insert_own on public.user_preferences;
create policy user_preferences_insert_own
  on public.user_preferences for insert to authenticated
  with check ((select auth.uid()) = user_id);

drop policy if exists user_preferences_update_own on public.user_preferences;
create policy user_preferences_update_own
  on public.user_preferences for update to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

-- Clients may read their own row and write preference columns only.
-- Timestamps are generated by PostgreSQL; anonymous callers get no access.
revoke all on table public.user_preferences from public, anon, authenticated;
grant select on table public.user_preferences to authenticated;
grant insert (user_id, show_animated_lyrics, equalizer_enabled,
  ambient_color_enabled, auto_download_enabled, audio_quality)
  on table public.user_preferences to authenticated;
grant update (user_id, show_animated_lyrics, equalizer_enabled,
  ambient_color_enabled, auto_download_enabled, audio_quality)
  on table public.user_preferences to authenticated;

-- Trigger-only function: clients do not need to invoke it directly.
revoke all on function public.set_user_preferences_updated_at() from public, anon, authenticated;

notify pgrst, 'reload schema';
commit;
